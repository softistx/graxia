#!/usr/bin/env bun
/**
 * `bun run plugin:index` writes the plugin's package index,
 * `plugins/graxia/skills/use-graxia/references/packages.md`, from each
 * published package's `package.json`, the public names its entry points export
 * (read from the source with the TypeScript checker) and the doc pages it
 * ships. `--check` exits 1 when the committed file is stale.
 * `plugin-index.spec.ts` also fails then.
 *
 * `render` is pure: it takes the data `readIndex` collects.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import ts from 'typescript';
import {
	byCodePoint,
	type Manifest,
	publishedPackages,
	ROOT,
} from './package-docs';

export const INDEX_PATH =
	'plugins/graxia/skills/use-graxia/references/packages.md';

export const FIX = 'run `bun run plugin:index`';

export type IndexEntry = {
	name: string;
	version: string;
	description: string;
	peers: { name: string; range: string; optional: boolean }[];
	subpaths: { path: string; names: string[] }[];
	docs: { file: string; title: string }[];
};

/** `workspace:^` becomes `^` plus the sibling's current version. */
const peersOf = (
	manifest: Manifest,
	versions: Map<string, string>,
): IndexEntry['peers'] =>
	Object.entries(manifest.peerDependencies ?? {})
		.map(([name, range]) => ({
			name,
			range: range.startsWith('workspace:')
				? `${range.slice('workspace:'.length)}${versions.get(name) ?? ''}`
				: range,
			optional: manifest.peerDependenciesMeta?.[name]?.optional === true,
		}))
		.sort((a, b) => byCodePoint(a.name, b.name));

const installLine = (entry: IndexEntry): string =>
	`bun add ${[entry.name, ...entry.peers.filter((p) => !p.optional).map((p) => p.name)].join(' ')}`;

/** One package's section. */
export function renderEntry(entry: IndexEntry): string {
	const peers =
		entry.peers.length === 0
			? 'none'
			: entry.peers
					.map(
						(p) =>
							`\`${p.name}\` \`${p.range}\`${p.optional ? ' (optional)' : ''}`,
					)
					.join(', ');
	const subpaths = entry.subpaths.flatMap((s) => [
		`- \`${s.path}\`: ${s.names.length === 0 ? 'no named export' : s.names.map((n) => `\`${n}\``).join(', ')}`,
	]);
	return [
		`## ${entry.name}`,
		'',
		`${entry.description} (${entry.version})`,
		'',
		`- Install: \`${installLine(entry)}\``,
		`- Peers: ${peers}`,
		'- Entry points and their public names:',
		...subpaths.map((line) => `  ${line}`),
		'- Docs, in the installed package:',
		...entry.docs.map(
			(d) => `  - \`node_modules/${entry.name}/${d.file}\`: ${d.title}`,
		),
		'',
	].join('\n');
}

/** The whole index file, as it must be committed. */
export function render(entries: IndexEntry[]): string {
	return [
		'<!-- GENERATED by scripts/plugin-index.ts (`bun run plugin:index`) from packages/*/package.json, their sources and docs. Do not edit by hand. -->',
		'',
		'# The graxia packages',
		'',
		'One entry per published package: what it is, how to install it, its peers, the public names of each entry point and the docs its tarball ships. Read the pages in `node_modules`: they match the installed version.',
		'',
		...[...entries]
			.sort((a, b) => byCodePoint(a.name, b.name))
			.map(renderEntry),
	].join('\n');
}

/** The source file an `exports` entry's types path comes from. */
export function sourceOf(typesPath: string): string {
	return typesPath.replace(/^\.\/dist\//, 'src/').replace(/\.d\.ts$/, '.ts');
}

const typesPathOf = (target: unknown): string | undefined =>
	typeof target === 'object' && target !== null
		? ((target as Record<string, unknown>)['types'] as string | undefined)
		: undefined;

/** The names a source module exports, sorted, as the checker resolves them. */
export function exportedNames(files: string[]): Map<string, string[]> {
	const program = ts.createProgram(files, {
		module: ts.ModuleKind.ESNext,
		moduleResolution: ts.ModuleResolutionKind.Bundler,
		target: ts.ScriptTarget.ES2022,
		skipLibCheck: true,
		noEmit: true,
		types: [],
	});
	const checker = program.getTypeChecker();
	const result = new Map<string, string[]>();
	for (const file of files) {
		const source = program.getSourceFile(file);
		const symbol = source && checker.getSymbolAtLocation(source);
		result.set(
			file,
			symbol
				? checker
						.getExportsOfModule(symbol)
						.map((s) => s.name)
						.filter((name) => name !== 'default')
						.sort(byCodePoint)
				: [],
		);
	}
	return result;
}

/** Reads the workspace into index entries. */
export function readIndex(root = ROOT): IndexEntry[] {
	const packages = publishedPackages(root);
	const versions = new Map(
		packages.map((p) => [p.manifest.name, p.manifest.version]),
	);
	return packages.map(({ folder, manifest, pages }) => {
		const keys = Object.keys(manifest.exports ?? {}).filter(
			(key) => key !== './package.json',
		);
		const sources = keys.map((key) => {
			const types = typesPathOf(manifest.exports?.[key]);
			return types ? join(root, 'packages', folder, sourceOf(types)) : '';
		});
		const names = exportedNames(sources.filter((s) => existsSync(s)));
		return {
			name: manifest.name,
			version: manifest.version,
			description: manifest.description ?? '',
			peers: peersOf(manifest, versions),
			subpaths: keys.map((key, i) => ({
				path: key === '.' ? manifest.name : `${manifest.name}${key.slice(1)}`,
				names: names.get(sources[i] as string) ?? [],
			})),
			docs: pages.map((p) => ({ file: p.file, title: p.title })),
		};
	});
}

export const buildIndex = (root = ROOT): string => render(readIndex(root));

if (import.meta.main) {
	const next = buildIndex();
	const path = join(ROOT, INDEX_PATH);
	if (process.argv.includes('--check')) {
		const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
		if (current !== next) {
			console.error(`${INDEX_PATH} is stale: ${FIX}`);
			process.exit(1);
		}
		console.log(`${INDEX_PATH} is current`);
	} else {
		writeFileSync(path, next);
		console.log(`wrote ${INDEX_PATH}`);
	}
}
